-- Create profile_answers table
------------------------
CREATE TABLE IF NOT EXISTS "public"."profile_answers" (
    "id" bigint NOT NULL,
    "answer_id" bigint,
    "profile_id" "uuid",
    "created_at" timestamp with time zone DEFAULT "now"(),
    "updated_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "poll_id" bigint
);

-- Alter table statements
------------------------
ALTER TABLE "public"."profile_answers" OWNER TO "postgres";
ALTER TABLE "public"."profile_answers" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."profile_answers_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY "public"."profile_answers" ADD CONSTRAINT "profile_answers_pkey" PRIMARY KEY ("id");
ALTER TABLE ONLY "public"."profile_answers" ADD CONSTRAINT "profile_answers_answer_id_fkey" FOREIGN KEY ("answer_id") REFERENCES "public"."answers"("id") ON DELETE CASCADE;
ALTER TABLE ONLY "public"."profile_answers" ADD CONSTRAINT "profile_answers_poll_id_fkey" FOREIGN KEY ("poll_id") REFERENCES "public"."polls"("id") ON DELETE CASCADE;
ALTER TABLE ONLY "public"."profile_answers" ADD CONSTRAINT "profile_answers_profile_id_fkey" FOREIGN KEY ("profile_id") REFERENCES "public"."profiles"("id");

-- Define triggers
------------------------
CREATE OR REPLACE TRIGGER "handle_updated_at" BEFORE UPDATE ON "public"."profile_answers" FOR EACH ROW EXECUTE FUNCTION "extensions"."moddatetime"('updated_at');

