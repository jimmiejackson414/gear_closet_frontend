-- Rate-limit log for Friends-page email invites.
-- Service-role only (no client policies); matches trip_invite_attempts.

CREATE TABLE public.friend_invite_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  email_count integer NOT NULL DEFAULT 1,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT friend_invite_attempts_email_count_positive CHECK (email_count > 0)
);

CREATE INDEX friend_invite_attempts_profile_created_idx
  ON public.friend_invite_attempts (profile_id, created_at DESC);

ALTER TABLE public.friend_invite_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.friend_invite_attempts FORCE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.friend_invite_attempts FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.friend_invite_attempts_id_seq FROM PUBLIC, anon, authenticated;

GRANT ALL ON TABLE public.friend_invite_attempts TO service_role;
GRANT ALL ON SEQUENCE public.friend_invite_attempts_id_seq TO service_role;
