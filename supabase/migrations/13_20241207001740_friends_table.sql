-- Create friends table
------------------------
CREATE TABLE IF NOT EXISTS "public"."friends" (
    "id" bigint NOT NULL,
    "created_at" timestamp with time zone DEFAULT "now"(),
    "updated_at" timestamp with time zone DEFAULT "now"(),
    "profile_id" "uuid",
    "friend_id" "uuid"
);

-- Alter table statements
------------------------
ALTER TABLE "public"."friends" OWNER TO "postgres";
ALTER TABLE "public"."friends" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."friends_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY "public"."friends" ADD CONSTRAINT "friends_pkey" PRIMARY KEY ("id");
ALTER TABLE "public"."friends" ADD CONSTRAINT "unique_friendship" UNIQUE ("friend_id", "profile_id");
ALTER TABLE ONLY "public"."friends" ADD CONSTRAINT "friends_friend_id_fkey" FOREIGN KEY ("friend_id") REFERENCES "public"."profiles"("id");
ALTER TABLE ONLY "public"."friends" ADD CONSTRAINT "friends_profile_id_fkey" FOREIGN KEY ("profile_id") REFERENCES "public"."profiles"("id");

-- Define triggers
------------------------
CREATE OR REPLACE TRIGGER "handle_updated_at" BEFORE UPDATE ON "public"."friends" FOR EACH ROW EXECUTE FUNCTION "extensions"."moddatetime"('updated_at');

-- Enable RLS
------------------------
ALTER TABLE "public"."friends" ENABLE ROW LEVEL SECURITY;

-- Define policies
------------------------
CREATE POLICY "View own friendships" ON "public"."friends"
FOR SELECT
TO authenticated
USING (
  profile_id = auth.uid() OR
  friend_id = auth.uid()
);

CREATE POLICY "Create friendships through requests" ON "public"."friends"
FOR INSERT
TO authenticated
WITH CHECK (
  profile_id = auth.uid() OR
  friend_id = auth.uid()
);

CREATE POLICY "Delete own friendships" ON "public"."friends"
FOR DELETE
TO authenticated
USING (
  profile_id = auth.uid() OR
  friend_id = auth.uid()
);

-- Search friends
------------------------
CREATE OR REPLACE FUNCTION search_friends_with_profile(search_term TEXT)
RETURNS TABLE (
  id BIGINT,
  created_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ,
  profile_id UUID,
  friend_id UUID,
  profile JSONB
) AS $$
BEGIN
  RETURN QUERY
  SELECT
    f.id,
    f.created_at,
    f.updated_at,
    f.profile_id,
    f.friend_id,
    to_jsonb(p) AS profile
  FROM friends f
  JOIN profiles p ON p.id = f.profile_id
  WHERE p.fts @@ plainto_tsquery('simple', search_term);
END;
$$ LANGUAGE plpgsql;

