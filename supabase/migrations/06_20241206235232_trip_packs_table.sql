-- Create trip_packs table
------------------------
CREATE TABLE IF NOT EXISTS "public"."trip_packs" (
    "id" bigint NOT NULL,
    "trip_id" bigint,
    "pack_id" bigint,
    "created_at" timestamp with time zone DEFAULT "now"(),
    "updated_at" timestamp with time zone DEFAULT "now"(),
    "profile_id" "uuid"
);

-- Alter trip_packs table
------------------------
ALTER TABLE "public"."trip_packs" OWNER TO "postgres";
ALTER TABLE "public"."trip_packs" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."trip_packs_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY "public"."trip_packs" ADD CONSTRAINT "trip_packs_pkey" PRIMARY KEY ("id");
ALTER TABLE ONLY "public"."trip_packs" ADD CONSTRAINT "trip_packs_pack_id_fkey" FOREIGN KEY ("pack_id") REFERENCES "public"."packs"("id");
ALTER TABLE ONLY "public"."trip_packs" ADD CONSTRAINT "trip_packs_trip_id_fkey" FOREIGN KEY ("trip_id") REFERENCES "public"."trips"("id");
ALTER TABLE ONLY "public"."trip_packs" ADD CONSTRAINT "trip_packs_profile_id_fkey" FOREIGN KEY ("profile_id") REFERENCES "public"."profiles"("id");

-- Define triggers
------------------------
CREATE OR REPLACE TRIGGER "handle_updated_at" BEFORE UPDATE ON "public"."trip_packs" FOR EACH ROW EXECUTE FUNCTION "extensions"."moddatetime"('updated_at');

-- Define policies
------------------------
-- View policy: Trip members can view trip_packs
CREATE POLICY "Trip members can view trip_packs" ON "public"."trip_packs"
FOR SELECT TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM trip_friends tf
    WHERE tf.trip_id = trip_packs.trip_id
    AND tf.profile_id = auth.uid()
    AND (
      tf.role = 'OWNER'
      OR (tf.role = 'MEMBER' AND tf.status = 'ACCEPTED')
    )
  )
);

-- Insert policy: Trip members can add packs they own or public packs
CREATE POLICY "Trip members can add their packs" ON "public"."trip_packs"
FOR INSERT TO authenticated
WITH CHECK (
  -- Must be a trip member
  EXISTS (
    SELECT 1 FROM trip_friends tf
    WHERE tf.trip_id = trip_id
    AND tf.profile_id = auth.uid()
    AND (
      tf.role = 'OWNER'
      OR (tf.role = 'MEMBER' AND tf.status = 'ACCEPTED')
    )
  )
  AND
  -- Must own the pack OR the pack must be public
  EXISTS (
    SELECT 1 FROM packs p
    WHERE p.id = pack_id
    AND (
      p.profile_id = auth.uid()
      OR NOT p.private
    )
  )
  -- Ensure profile_id matches the authenticated user
  AND profile_id = auth.uid()
);

-- Update policy: Trip members can update their own pack associations
CREATE POLICY "Trip members can update their pack associations" ON "public"."trip_packs"
FOR UPDATE TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM trip_friends tf
    WHERE tf.trip_id = trip_packs.trip_id
    AND tf.profile_id = auth.uid()
    AND (
      tf.role = 'OWNER'
      OR (tf.role = 'MEMBER' AND tf.status = 'ACCEPTED')
    )
  )
  AND profile_id = auth.uid()
);

-- Delete policy: Trip members can remove their own pack associations
CREATE POLICY "Trip members can remove their pack associations" ON "public"."trip_packs"
FOR DELETE TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM trip_friends tf
    WHERE tf.trip_id = trip_packs.trip_id
    AND tf.profile_id = auth.uid()
    AND (
      tf.role = 'OWNER'
      OR (tf.role = 'MEMBER' AND tf.status = 'ACCEPTED')
    )
  )
  AND profile_id = auth.uid()
);

