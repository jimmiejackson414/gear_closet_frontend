-- Define types
------------------------
CREATE TYPE "public"."category_item_position" AS (
  category_item_id INT,
  category_id INT,
  item_id INT,
  new_position INT
);
ALTER TYPE "public"."category_item_position" OWNER TO "postgres";

-- Create category_items table
------------------------
CREATE TABLE IF NOT EXISTS "public"."category_items" (
    "id" bigint NOT NULL,
    "category_id" bigint,
    "item_id" bigint,
    "position" bigint,
    "created_at" timestamp with time zone DEFAULT "now"(),
    "updated_at" timestamp with time zone DEFAULT "now"()
);

-- Alter category_items table
------------------------
ALTER TABLE "public"."category_items" OWNER TO "postgres";
ALTER TABLE "public"."category_items" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."category_items_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY "public"."category_items" ADD CONSTRAINT "category_items_pkey" PRIMARY KEY ("id");
ALTER TABLE ONLY "public"."category_items" ADD CONSTRAINT "category_items_category_id_fkey" FOREIGN KEY ("category_id") REFERENCES "public"."categories"("id") ON DELETE CASCADE;
ALTER TABLE ONLY "public"."category_items" ADD CONSTRAINT "category_items_item_id_fkey" FOREIGN KEY ("item_id") REFERENCES "public"."items"("id") ON DELETE NO ACTION;
ALTER TABLE "public"."category_items" ADD CONSTRAINT "unique_category_position" UNIQUE ("category_id", "position");

-- Define triggers
------------------------
CREATE OR REPLACE TRIGGER "handle_updated_at" BEFORE UPDATE ON "public"."category_items" FOR EACH ROW EXECUTE FUNCTION "extensions"."moddatetime"('updated_at');

-- Enable RLS
------------------------
ALTER TABLE "public"."category_items" ENABLE ROW LEVEL SECURITY;

-- Define policies
------------------------
-- Allow viewing category_items if you can view both the category and item
CREATE POLICY "View allowed category_items" ON "public"."category_items"
FOR SELECT USING (
  EXISTS (
    SELECT 1 FROM categories c
    JOIN packs p ON p.id = c.pack_id
    WHERE c.id = category_items.category_id
    AND (
      -- Pack owner can view
      p.profile_id = auth.uid()
      OR
      -- Public packs can be viewed
      NOT p.private
      OR
      -- Trip members can view
      EXISTS (
        SELECT 1 FROM trip_friends tf1
        JOIN trip_friends tf2 ON tf2.trip_id = tf1.trip_id
        WHERE tf1.profile_id = auth.uid()
        AND tf2.profile_id = p.profile_id
        AND (
          tf1.role = 'OWNER' OR (tf1.role = 'MEMBER' AND tf1.status = 'ACCEPTED')
        )
        AND (
          tf2.role = 'OWNER' OR (tf2.role = 'MEMBER' AND tf2.status = 'ACCEPTED')
        )
      )
    )
  )
);

-- Allow creating category_items if:
-- 1. You own the pack that contains the category
-- 2. You own the item being added
CREATE POLICY "Add items to categories" ON "public"."category_items"
FOR INSERT WITH CHECK (
  EXISTS (
    SELECT 1 FROM categories c
    JOIN packs p ON p.id = c.pack_id
    WHERE c.id = category_id
    AND p.profile_id = auth.uid()
  )
  AND
  EXISTS (
    SELECT 1 FROM items i
    WHERE i.id = item_id
    AND i.profile_id = auth.uid()
  )
);

-- Allow updating category_items if you own the pack
CREATE POLICY "Update category items" ON "public"."category_items"
FOR UPDATE USING (
  EXISTS (
    SELECT 1 FROM categories c
    JOIN packs p ON p.id = c.pack_id
    WHERE c.id = category_items.category_id
    AND p.profile_id = auth.uid()
  )
);

-- Allow deleting category_items if you own the pack
CREATE POLICY "Delete category items" ON "public"."category_items"
FOR DELETE USING (
  EXISTS (
    SELECT 1 FROM categories c
    JOIN packs p ON p.id = c.pack_id
    WHERE c.id = category_items.category_id
    AND p.profile_id = auth.uid()
  )
);

