-- Define enums
------------------------
CREATE TYPE "public"."trip_details_type" AS ENUM (
    'HIKE',
    'TRIP'
);

-- Create trip_details table
------------------------
CREATE TABLE IF NOT EXISTS "public"."trip_details" (
    "id" bigint NOT NULL,
    "title" character varying,
    "url" character varying,
    "value" character varying,
    "type" "public"."trip_details_type" DEFAULT 'HIKE'::"public"."trip_details_type" NOT NULL,
    "trip_id" bigint,
    "created_at" timestamp with time zone DEFAULT "now"(),
    "updated_at" timestamp with time zone DEFAULT "now"() NOT NULL
);

-- Alter table statements
------------------------
ALTER TABLE "public"."trip_details" OWNER TO "postgres";
ALTER TABLE "public"."trip_details" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."trip_details_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY "public"."trip_details" ADD CONSTRAINT "trip_details_pkey" PRIMARY KEY ("id");
ALTER TABLE ONLY "public"."trip_details" ADD CONSTRAINT "trip_details_trip_id_fkey" FOREIGN KEY ("trip_id") REFERENCES "public"."trips"("id");
ALTER TYPE "public"."trip_details_type" OWNER TO "postgres";

-- Define triggers
------------------------
CREATE OR REPLACE TRIGGER "handle_updated_at" BEFORE UPDATE ON "public"."trip_details" FOR EACH ROW EXECUTE FUNCTION "extensions"."moddatetime"('updated_at');

-- Enable RLS
------------------------
ALTER TABLE "public"."trip_details" ENABLE ROW LEVEL SECURITY;

-- Define policies
------------------------
-- Allow trip members to read trip details
CREATE POLICY "Trip members can view trip details" ON "public"."trip_details"
FOR SELECT USING (
  EXISTS (
    SELECT 1 FROM trip_friends
    WHERE trip_friends.trip_id = trip_id
    AND trip_friends.profile_id = auth.uid()
    AND trip_friends.status = 'ACCEPTED'
  )
);

-- Allow trip members to manage trip details
CREATE POLICY "Trip members can manage trip details" ON "public"."trip_details"
FOR ALL USING (
  EXISTS (
    SELECT 1 FROM trip_friends
    WHERE trip_friends.trip_id = trip_id
    AND trip_friends.profile_id = auth.uid()
    AND trip_friends.status = 'ACCEPTED'
  )
);

-- Grant permissions
------------------------
GRANT ALL ON TABLE "public"."trip_details" TO "authenticated";
GRANT ALL ON TABLE "public"."trip_details" TO "service_role";
GRANT ALL ON SEQUENCE "public"."trip_details_id_seq" TO "authenticated";
GRANT ALL ON SEQUENCE "public"."trip_details_id_seq" TO "service_role";

