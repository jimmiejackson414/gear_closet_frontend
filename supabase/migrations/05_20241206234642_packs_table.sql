-- Define types and enums
------------------------
CREATE TYPE "public"."theme" AS ENUM (
    'BLUE6',
    'BLUEGREEN6',
    'BREEZE6',
    'CELESTIAL6',
    'CIRCUIT6',
    'DAMASK6',
    'DEPTH6',
    'FLOW6',
    'FORTE6',
    'GENESIS6',
    'GRAYSCALE6',
    'IONBOARDROOM6',
    'KILTER6',
    'TABLEAU10',
    'COLORBLIND10',
    'JEWELBRIGHT9',
    'HUECIRCLE19'
);
ALTER TYPE "public"."theme" OWNER TO "postgres";

-- Create packs table
------------------------
CREATE TABLE IF NOT EXISTS "public"."packs" (
    "id" bigint NOT NULL,
    "name" character varying,
    "slug" character varying,
    "created_at" timestamp with time zone DEFAULT "now"(),
    "updated_at" timestamp with time zone DEFAULT "now"(),
    "profile_id" "uuid" NOT NULL,
    "theme" "public"."theme" DEFAULT 'BLUE6'::"public"."theme",
    "private" boolean DEFAULT false NOT NULL,
    "allow_comments" boolean DEFAULT false NOT NULL
);

-- Alter statements
------------------------
ALTER TABLE "public"."packs" OWNER TO "postgres";
ALTER TABLE "public"."packs" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."packs_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY "public"."packs" ADD CONSTRAINT "packs_pkey" PRIMARY KEY ("id");
ALTER TABLE ONLY "public"."packs" ADD CONSTRAINT "packs_slug_key" UNIQUE ("slug");
ALTER TABLE ONLY "public"."packs" ADD CONSTRAINT "packs_profile_id_fkey" FOREIGN KEY ("profile_id") REFERENCES "public"."profiles"("id");

-- Define triggers
------------------------
CREATE OR REPLACE TRIGGER "generate_slug_for_packs" BEFORE INSERT ON "public"."packs" FOR EACH ROW EXECUTE FUNCTION "public"."generate_slug"();
CREATE OR REPLACE TRIGGER "handle_updated_at" BEFORE UPDATE ON "public"."packs" FOR EACH ROW EXECUTE FUNCTION "extensions"."moddatetime"('updated_at');

-- Define policies
------------------------
-- View policy: Anyone (including anonymous users) can view public packs
CREATE POLICY "Anyone can view public packs" ON "public"."packs"
FOR SELECT TO public
USING (NOT private);

-- View policy: Authenticated users can view their own packs
CREATE POLICY "Users can view own packs" ON "public"."packs"
FOR SELECT TO authenticated
USING (profile_id = auth.uid());

-- Insert policy: Authenticated users can create packs
CREATE POLICY "Users can create packs" ON "public"."packs"
FOR INSERT TO authenticated
WITH CHECK (
  auth.role() = 'authenticated'
  AND profile_id = auth.uid()
);

-- Update policy: Users can update their own packs
CREATE POLICY "Users can update own packs" ON "public"."packs"
FOR UPDATE TO authenticated
USING (profile_id = auth.uid());

-- Delete policy: Users can delete their own packs
CREATE POLICY "Users can delete own packs" ON "public"."packs"
FOR DELETE TO authenticated
USING (profile_id = auth.uid());

