-- Create notifications table
------------------------
CREATE TABLE IF NOT EXISTS "public"."notifications" (
    "id" bigint NOT NULL,
    "title" character varying,
    "content" "text",
    "read_on_date" timestamp with time zone,
    "created_at" timestamp with time zone DEFAULT "now"(),
    "updated_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "profile_id" "uuid",
    "sender_id" "uuid"
);

-- Alter table statements
------------------------
ALTER TABLE "public"."notifications" OWNER TO "postgres";
ALTER TABLE "public"."notifications"
ALTER COLUMN "sender_id" SET DEFAULT '00000000-0000-0000-0000-000000000000';
ALTER TABLE "public"."notifications" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."notifications_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY "public"."notifications" ADD CONSTRAINT "notifications_pkey" PRIMARY KEY ("id");
ALTER TABLE ONLY "public"."notifications"
    ADD CONSTRAINT "notifications_profile_id_fkey" FOREIGN KEY ("profile_id") REFERENCES "public"."profiles"("id") ON DELETE CASCADE;

ALTER TABLE ONLY "public"."notifications"
    ADD CONSTRAINT "notifications_sender_id_fkey" FOREIGN KEY ("sender_id") REFERENCES "public"."profiles"("id") ON DELETE CASCADE;

-- Define triggers
------------------------
CREATE OR REPLACE TRIGGER "handle_updated_at" BEFORE UPDATE ON "public"."notifications" FOR EACH ROW EXECUTE FUNCTION "extensions"."moddatetime"('updated_at');

-- Enable RLS
------------------------
ALTER TABLE "public"."notifications" ENABLE ROW LEVEL SECURITY;

-- Define policies
------------------------
CREATE POLICY "Users can view own notifications" ON "public"."notifications"
FOR SELECT
TO authenticated
USING (
  profile_id = auth.uid()
);

CREATE POLICY "Users can create notifications" ON "public"."notifications"
FOR INSERT
TO authenticated
WITH CHECK (
  sender_id = auth.uid()
);

CREATE POLICY "Users can update own notifications" ON "public"."notifications"
FOR UPDATE
TO authenticated
USING (
  profile_id = auth.uid()
)
WITH CHECK (
  profile_id = auth.uid()
);

CREATE POLICY "Users can delete own notifications" ON "public"."notifications"
FOR DELETE
TO authenticated
USING (
  profile_id = auth.uid()
);

CREATE POLICY "Service role can manage notifications" ON "public"."notifications"
FOR ALL
TO service_role
USING (true)
WITH CHECK (true);

-- Grant permissions
------------------------
GRANT ALL ON TABLE "public"."notifications" TO "authenticated";
GRANT ALL ON TABLE "public"."notifications" TO "service_role";
GRANT ALL ON SEQUENCE "public"."notifications_id_seq" TO "authenticated";
GRANT ALL ON SEQUENCE "public"."notifications_id_seq" TO "service_role";