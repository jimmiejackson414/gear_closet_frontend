-- Create comments table
------------------------
CREATE TABLE IF NOT EXISTS "public"."comments" (
    "id" bigint NOT NULL,
    "text" "text",
    "profile_id" "uuid" NOT NULL,
    "pack_id" bigint NOT NULL,
    "deleted_at" timestamp with time zone,
    "created_at" timestamp with time zone DEFAULT "now"(),
    "updated_at" timestamp with time zone DEFAULT "now"()
);

-- Alter table statements
------------------------
ALTER TABLE "public"."comments" OWNER TO "postgres";
ALTER TABLE "public"."comments" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."comments_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY "public"."comments" ADD CONSTRAINT "comments_id_key" UNIQUE ("id");
ALTER TABLE ONLY "public"."comments" ADD CONSTRAINT "comments_pkey" PRIMARY KEY ("id");
ALTER TABLE ONLY "public"."comments" ADD CONSTRAINT "comments_pack_id_fkey" FOREIGN KEY ("pack_id") REFERENCES "public"."packs"("id");
ALTER TABLE ONLY "public"."comments" ADD CONSTRAINT "comments_profile_id_fkey" FOREIGN KEY ("profile_id") REFERENCES "public"."profiles"("id");

-- Define triggers
------------------------
CREATE OR REPLACE TRIGGER "handle_updated_at" BEFORE UPDATE ON "public"."comments" FOR EACH ROW EXECUTE FUNCTION "extensions"."moddatetime"('updated_at');

-- Grant permissions
------------------------
GRANT ALL ON TABLE "public"."comments" TO "anon";
GRANT ALL ON TABLE "public"."comments" TO "authenticated";
GRANT ALL ON TABLE "public"."comments" TO "service_role";
GRANT ALL ON SEQUENCE "public"."comments_id_seq" TO "anon";
GRANT ALL ON SEQUENCE "public"."comments_id_seq" TO "authenticated";
GRANT ALL ON SEQUENCE "public"."comments_id_seq" TO "service_role";