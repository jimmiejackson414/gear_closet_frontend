-- Issue #43: pending trip invitations for emails without an account.
-- Tokens are hashed at rest. Claim is server/RPC only (no client claim policy).

CREATE TYPE public.trip_invitation_status AS ENUM (
  'PENDING',
  'CLAIMED',
  'CANCELED'
);

ALTER TYPE public.trip_invitation_status OWNER TO postgres;

CREATE TABLE public.trip_invitations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id bigint NOT NULL REFERENCES public.trips(id) ON DELETE CASCADE,
  email text NOT NULL,
  invited_by_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  token_hash text NOT NULL,
  status public.trip_invitation_status NOT NULL DEFAULT 'PENDING'::public.trip_invitation_status,
  expires_at timestamp with time zone NOT NULL,
  claimed_profile_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT trip_invitations_email_not_blank CHECK (length(trim(email)) > 0),
  CONSTRAINT trip_invitations_token_hash_sha256 CHECK (token_hash ~ '^[0-9a-f]{64}$')
);

CREATE UNIQUE INDEX trip_invitations_token_hash_key
  ON public.trip_invitations (token_hash);

CREATE UNIQUE INDEX trip_invitations_trip_email_pending_idx
  ON public.trip_invitations (trip_id, lower(email))
  WHERE status = 'PENDING'::public.trip_invitation_status;

CREATE INDEX trip_invitations_pending_email_idx
  ON public.trip_invitations (lower(email))
  WHERE status = 'PENDING'::public.trip_invitation_status;

CREATE INDEX trip_invitations_trip_id_idx
  ON public.trip_invitations (trip_id);

CREATE INDEX trip_invitations_invited_by_id_idx
  ON public.trip_invitations (invited_by_id);

CREATE INDEX trip_invitations_claimed_profile_id_idx
  ON public.trip_invitations (claimed_profile_id);

ALTER TABLE public.trip_invitations OWNER TO postgres;
ALTER TABLE public.trip_invitations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trip_invitations FORCE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.trip_invitations FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.trip_invitations_id_seq FROM PUBLIC, anon, authenticated;

GRANT ALL ON TABLE public.trip_invitations TO service_role;
GRANT ALL ON SEQUENCE public.trip_invitations_id_seq TO service_role;

-- Owners can list/cancel pending rows. token_hash is omitted from the column grant.
GRANT SELECT (
  id,
  trip_id,
  email,
  invited_by_id,
  status,
  expires_at,
  claimed_profile_id,
  created_at,
  updated_at
) ON public.trip_invitations TO authenticated;
GRANT DELETE ON public.trip_invitations TO authenticated;

CREATE POLICY trip_invitations_select_owner
  ON public.trip_invitations
  FOR SELECT
  TO authenticated
  USING (private.owns_trip(trip_id));

CREATE POLICY trip_invitations_delete_owner
  ON public.trip_invitations
  FOR DELETE
  TO authenticated
  USING (
    private.owns_trip(trip_id)
    AND status = 'PENDING'::public.trip_invitation_status
  );

-- ---------------------------------------------------------------------------
-- Auto-claim matching pending invites when a user signs up.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION private.claim_pending_trip_invitations_by_email(
  p_profile_id uuid,
  p_email text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  invite record;
BEGIN
  IF p_profile_id IS NULL OR p_email IS NULL OR length(trim(p_email)) = 0 THEN
    RETURN;
  END IF;

  FOR invite IN
    SELECT ti.id, ti.trip_id, ti.invited_by_id
    FROM public.trip_invitations ti
    WHERE lower(ti.email) = lower(p_email)
      AND ti.status = 'PENDING'::public.trip_invitation_status
      AND ti.expires_at > now()
  LOOP
    INSERT INTO public.trip_friends (trip_id, profile_id, status, invited_by_id)
    VALUES (
      invite.trip_id,
      p_profile_id,
      'PENDING'::public.trip_friend_status,
      invite.invited_by_id
    )
    ON CONFLICT (trip_id, profile_id) DO NOTHING;

    UPDATE public.trip_invitations
    SET
      status = 'CLAIMED'::public.trip_invitation_status,
      claimed_profile_id = p_profile_id,
      updated_at = now()
    WHERE id = invite.id
      AND status = 'PENDING'::public.trip_invitation_status;

    INSERT INTO public.notifications (title, content, read_on_date, profile_id, sender_id)
    VALUES (
      'You''ve been invited to a trip!',
      'You were invited to a trip on Gear Closet.',
      NULL,
      p_profile_id,
      invite.invited_by_id
    );
  END LOOP;
END;
$$;

ALTER FUNCTION private.claim_pending_trip_invitations_by_email(uuid, text) OWNER TO postgres;

REVOKE ALL ON FUNCTION private.claim_pending_trip_invitations_by_email(uuid, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION private.claim_pending_trip_invitations_by_email(uuid, text)
  TO postgres, service_role;

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
  starter_pack_id bigint;
  starter_trip_id bigint;
BEGIN
  INSERT INTO public.profiles (id, email, image, role, measuring_system)
  VALUES (
    NEW.id,
    NEW.email,
    NULL,
    'USER'::public.user_role,
    'IMPERIAL'::public.measuring_system
  )
  ON CONFLICT (id) DO UPDATE SET email = NEW.email;

  INSERT INTO public.notifications (title, content, read_on_date, profile_id, sender_id)
  VALUES (
    'Welcome!',
    'Welcome to Gear Closet! This is where you will receive all of your important updates.',
    NULL,
    NEW.id,
    '00000000-0000-0000-0000-000000000000'
  );

  INSERT INTO public.packs (name, profile_id, theme, private, allow_comments)
  VALUES (
    'My first pack',
    NEW.id,
    'BLUE6'::public.theme,
    true,
    false
  )
  RETURNING id INTO starter_pack_id;

  INSERT INTO public.trips (
    name,
    description,
    starting_point,
    ending_point,
    starting_date,
    ending_date,
    profile_id
  )
  VALUES (
    'My first trip',
    'Edit this trip to plan your next backpacking adventure.',
    'Starting point',
    'Ending point',
    now() + interval '30 days',
    now() + interval '33 days',
    NEW.id
  )
  RETURNING id INTO starter_trip_id;

  INSERT INTO public.trip_packs (trip_id, pack_id, profile_id)
  VALUES (starter_trip_id, starter_pack_id, NEW.id);

  PERFORM private.claim_pending_trip_invitations_by_email(NEW.id, NEW.email);

  RETURN NEW;
END;
$$;

ALTER FUNCTION public.handle_new_user() OWNER TO postgres;

REVOKE ALL ON FUNCTION public.handle_new_user() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.handle_new_user() FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION public.handle_new_user() TO postgres, service_role;

-- ---------------------------------------------------------------------------
-- Planning payload: pending email invites for the trip owner (no token_hash).
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.get_planning_page_data(p_trip_id bigint)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
  DECLARE
    uid uuid := (SELECT private.uid());
    trips_data JSON;
    trip_packs_data JSON;
    trip_details_data JSON;
    todos_data JSON;
    shopping_items_data JSON;
    friends_data JSON;
    pending_invites_data JSON;
    poll_data JSON;
    dynamic_trip_id BIGINT;
    trip_owner_id uuid;
  BEGIN
    IF uid IS NULL THEN
      RETURN jsonb_build_object(
        'trips', '[]'::json,
        'pack', '[]'::json,
        'trip_details', '[]'::json,
        'todos', '[]'::json,
        'shopping_items', '[]'::json,
        'friends', '[]'::json,
        'pending_invites', '[]'::json,
        'poll', null
      );
    END IF;

    SELECT json_agg(row_to_json(sub.*)) INTO trips_data
    FROM (
      SELECT t.*
      FROM public.trips t
      WHERE t.profile_id = uid
        OR EXISTS (
          SELECT 1
          FROM public.trip_friends tf
          WHERE tf.trip_id = t.id
            AND tf.profile_id = uid
            AND tf.status = 'ACCEPTED'::public.trip_friend_status
        )
      ORDER BY (t.profile_id = uid) DESC, t.locked_at NULLS FIRST, t.created_at ASC
    ) sub;

    IF p_trip_id = 0 THEN
      SELECT COALESCE((
        SELECT t.id
        FROM public.trips t
        WHERE t.profile_id = uid
          OR EXISTS (
            SELECT 1
            FROM public.trip_friends tf
            WHERE tf.trip_id = t.id
              AND tf.profile_id = uid
              AND tf.status = 'ACCEPTED'::public.trip_friend_status
          )
        ORDER BY (t.profile_id = uid) DESC, t.locked_at NULLS FIRST, t.created_at ASC
        LIMIT 1
      ), 0) INTO dynamic_trip_id;
    ELSE
      dynamic_trip_id := p_trip_id;
    END IF;

    IF dynamic_trip_id <> 0 AND NOT private.can_access_planning_trip(dynamic_trip_id) THEN
      dynamic_trip_id := 0;
    END IF;

    SELECT t.profile_id INTO trip_owner_id
    FROM public.trips t
    WHERE t.id = dynamic_trip_id;

    SELECT (COALESCE(json_agg(
      json_build_object(
        'id', pack.id,
        'name', pack.name,
        'slug', pack.slug,
        'created_at', pack.created_at,
        'updated_at', pack.updated_at,
        'profile_id', pack.profile_id,
        'theme', pack.theme,
        'private', pack.private,
        'allow_comments', pack.allow_comments,
        'locked_at', pack.locked_at,
        'categories', (
          SELECT COALESCE(json_agg(json_build_object(
            'id', c.id,
            'created_at', c.created_at,
            'name', c.name,
            'unit', c.unit,
            'slug', c.slug,
            'pack_id', c.pack_id,
            'updated_at', c.updated_at,
            'category_items', (
              SELECT COALESCE(json_agg(json_build_object(
                'id', ci.id,
                'category_id', ci.category_id,
                'item_id', ci.item_id,
                'position', ci.position,
                'created_at', ci.created_at,
                'updated_at', ci.updated_at,
                'item', row_to_json(i.*)
              )), '[]'::JSON)
              FROM public.category_items ci
              JOIN public.items i ON ci.item_id = i.id
              WHERE ci.category_id = c.id
            )
          )), '[]'::JSON)
          FROM public.categories c
          WHERE c.pack_id = pack.id
        )
      )
    ), '[]'::JSON) -> 0) INTO trip_packs_data
    FROM public.trip_packs tp
    JOIN public.packs pack ON tp.pack_id = pack.id
    WHERE dynamic_trip_id <> 0
      AND tp.trip_id = dynamic_trip_id
      AND tp.profile_id = trip_owner_id;

    SELECT COALESCE(json_agg(row_to_json(td.*)), '[]'::JSON) INTO trip_details_data
    FROM public.trip_details td
    WHERE td.trip_id = dynamic_trip_id;

    SELECT COALESCE(json_agg(row_to_json(todo.*)), '[]'::JSON) INTO todos_data
    FROM public.todos todo
    WHERE todo.trip_id = dynamic_trip_id;

    SELECT COALESCE(json_agg(row_to_json(si.*)), '[]'::JSON) INTO shopping_items_data
    FROM public.shopping_list_items si
    WHERE si.trip_id = dynamic_trip_id;

    SELECT COALESCE(json_agg(json_build_object(
      'id', tf.id,
      'trip_id', tf.trip_id,
      'profile_id', tf.profile_id,
      'invited_by_id', tf.invited_by_id,
      'status', tf.status,
      'accepted_invite_on', tf.accepted_invite_on,
      'created_at', tf.created_at,
      'updated_at', tf.updated_at,
      'friend_profile', row_to_json(p.*),
      'friend_trip_packs', (
        SELECT COALESCE(json_agg(row_to_json(tp.*)), '[]'::JSON)
        FROM public.trip_packs tp
        WHERE tp.profile_id = tf.profile_id
          AND tp.trip_id = dynamic_trip_id
      )
    )), '[]'::JSON) INTO friends_data
    FROM public.trip_friends tf
    JOIN public.profiles p ON tf.profile_id = p.id
    WHERE dynamic_trip_id <> 0
      AND tf.trip_id = dynamic_trip_id;

    IF dynamic_trip_id <> 0 AND trip_owner_id = uid THEN
      SELECT COALESCE(json_agg(json_build_object(
        'id', ti.id,
        'trip_id', ti.trip_id,
        'email', ti.email,
        'status', ti.status,
        'expires_at', ti.expires_at,
        'created_at', ti.created_at
      ) ORDER BY ti.created_at DESC), '[]'::JSON)
      INTO pending_invites_data
      FROM public.trip_invitations ti
      WHERE ti.trip_id = dynamic_trip_id
        AND ti.status = 'PENDING'::public.trip_invitation_status;
    ELSE
      pending_invites_data := '[]'::JSON;
    END IF;

    SELECT json_build_object(
      'id', p.id::integer,
      'trip_id', p.trip_id::integer,
      'profile_id', p.profile_id::uuid,
      'question', (SELECT row_to_json(q.*) FROM public.questions q WHERE q.poll_id = p.id),
      'answers', COALESCE((SELECT json_agg(row_to_json(a.*)) FROM public.answers a WHERE a.question_id = q.id), '[]'),
      'votes', COALESCE((SELECT json_agg(row_to_json(pa.*)) FROM public.profile_answers pa WHERE pa.poll_id = p.id), '[]')
    ) INTO poll_data
    FROM public.polls p
    JOIN public.questions q ON p.id = q.poll_id
    WHERE p.trip_id = dynamic_trip_id
    LIMIT 1;

    RETURN jsonb_build_object(
      'trips', trips_data,
      'pack', trip_packs_data,
      'trip_details', trip_details_data,
      'todos', todos_data,
      'shopping_items', shopping_items_data,
      'friends', friends_data,
      'pending_invites', pending_invites_data,
      'poll', poll_data
    );
  END;
$$;

REVOKE ALL ON FUNCTION public.get_planning_page_data(bigint) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.get_planning_page_data(bigint) FROM anon;
GRANT EXECUTE ON FUNCTION public.get_planning_page_data(bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION public.get_planning_page_data(bigint) TO service_role;
