-- Define types and enums
------------------------
CREATE TYPE "public"."trip_friend_status" AS ENUM (
    'ACCEPTED',
    'DECLINED',
    'PENDING'
);
ALTER TYPE "public"."trip_friend_status" OWNER TO "postgres";

CREATE TYPE "public"."trip_friend_role" as ENUM (
  'OWNER',
  'MEMBER'
)
ALTER TYPE "public"."trip_friend_role" OWNER TO "postgres";

-- Create trip_friends table
------------------------
CREATE TABLE IF NOT EXISTS "public"."trip_friends" (
    "id" BIGINT NOT NULL,
    "trip_id" BIGINT,
    "accepted_invite_on" TIMESTAMP WITH TIME ZONE,
    "created_at" TIMESTAMP WITH TIME ZONE DEFAULT "now"(),
    "status" "public"."trip_friend_status" DEFAULT 'PENDING'::"public"."trip_friend_status",
    "profile_id" UUID NOT NULL, -- Represents the friend
    "invited_by_id" UUID, -- Represents the inviter
    "invite_token" CHARACTER VARYING,
    "role" "public"."trip_friend_role" DEFAULT 'MEMBER'::"public"."trip_friend_role" NOT NULL,
    "updated_at" TIMESTAMP WITH TIME ZONE DEFAULT "now"() NOT NULL
);

-- Alter trip_friends table
------------------------
ALTER TABLE "public"."trip_friends" OWNER TO "postgres";
ALTER TABLE "public"."trip_friends" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."trip_friends_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY "public"."trip_friends" ADD CONSTRAINT "trip_friends_pkey" PRIMARY KEY ("id");
ALTER TABLE ONLY "public"."trip_friends" ADD CONSTRAINT "trip_friends_trip_id_fkey" FOREIGN KEY ("trip_id") REFERENCES "public"."trips"("id");
ALTER TABLE ONLY "public"."trip_friends" ADD CONSTRAINT "trip_friends_profile_id_fkey" FOREIGN KEY ("profile_id") REFERENCES "public"."profiles"("id");
ALTER TABLE ONLY "public"."trip_friends" ADD CONSTRAINT "trip_friends_invited_by_id_fkey" FOREIGN KEY ("invited_by_id") REFERENCES "public"."profiles"("id");

-- Define triggers
------------------------
CREATE OR REPLACE TRIGGER "handle_updated_at" BEFORE UPDATE ON "public"."trip_friends" FOR EACH ROW EXECUTE FUNCTION "extensions"."moddatetime"('updated_at');

-- Define policies
------------------------
CREATE POLICY "Enable CRUD for authenticated profiles only" ON "public"."trip_friends" WITH CHECK (("auth"."role"() = 'authenticated'::"text"));

-- Grant permissions
------------------------
GRANT ALL ON TABLE "public"."trip_friends" TO "anon";
GRANT ALL ON TABLE "public"."trip_friends" TO "authenticated";
GRANT ALL ON TABLE "public"."trip_friends" TO "service_role";
GRANT ALL ON SEQUENCE "public"."trip_friends_id_seq" TO "anon";
GRANT ALL ON SEQUENCE "public"."trip_friends_id_seq" TO "authenticated";
GRANT ALL ON SEQUENCE "public"."trip_friends_id_seq" TO "service_role";