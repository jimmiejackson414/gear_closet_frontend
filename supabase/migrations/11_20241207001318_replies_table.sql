-- Create replies table
------------------------
CREATE TABLE IF NOT EXISTS "public"."replies" (
    "id" bigint NOT NULL,
    "comment_id" bigint NOT NULL,
    "profile_id" "uuid" NOT NULL,
    "text" "text",
    "deleted_at" timestamp with time zone,
    "created_at" timestamp with time zone DEFAULT ("now"() AT TIME ZONE 'utc'::"text"),
    "updated_at" timestamp with time zone DEFAULT ("now"() AT TIME ZONE 'utc'::"text")
);

-- Alter table statements
------------------------
ALTER TABLE "public"."replies" OWNER TO "postgres";
ALTER TABLE "public"."replies" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."replies_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY "public"."replies" ADD CONSTRAINT "replies_id_key" UNIQUE ("id");
ALTER TABLE ONLY "public"."replies" ADD CONSTRAINT "replies_pkey" PRIMARY KEY ("id");
ALTER TABLE ONLY "public"."replies" ADD CONSTRAINT "replies_comment_id_fkey" FOREIGN KEY ("comment_id") REFERENCES "public"."comments"("id");
ALTER TABLE ONLY "public"."replies" ADD CONSTRAINT "replies_profile_id_fkey" FOREIGN KEY ("profile_id") REFERENCES "public"."profiles"("id");

-- Define triggers
------------------------
CREATE OR REPLACE TRIGGER "handle_updated_at" BEFORE UPDATE ON "public"."replies" FOR EACH ROW EXECUTE FUNCTION "extensions"."moddatetime"('updated_at');

-- Grant permissions
------------------------
GRANT ALL ON TABLE "public"."replies" TO "anon";
