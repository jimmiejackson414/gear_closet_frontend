-- Define enums
------------------------
CREATE TYPE "public"."resource_type" AS ENUM (
    'USER',
    'GROUP'
);

-- Create shopping_list_items table
------------------------
CREATE TABLE IF NOT EXISTS "public"."shopping_list_items" (
    "id" bigint NOT NULL,
    "title" character varying,
    "completed" boolean DEFAULT false NOT NULL,
    "quantity" bigint DEFAULT '0'::bigint,
    "trip_id" bigint,
    "created_at" timestamp with time zone DEFAULT "now"(),
    "updated_at" timestamp with time zone DEFAULT "now"(),
    "resource_type" "public"."resource_type" DEFAULT 'USER'::"public"."resource_type" NOT NULL,
    "profile_id" "uuid"
);

-- Alter table statements
------------------------
ALTER TABLE "public"."shopping_list_items" OWNER TO "postgres";
ALTER TABLE "public"."shopping_list_items" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."shopping_list_items_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY "public"."shopping_list_items" ADD CONSTRAINT "shopping_list_items_pkey" PRIMARY KEY ("id");
ALTER TABLE "public"."shopping_list_items"
ADD CONSTRAINT shopping_list_profile_id_check CHECK (
  (resource_type = 'USER' AND profile_id IS NOT NULL) OR
  resource_type = 'GROUP'
);
ALTER TABLE ONLY "public"."shopping_list_items" ADD CONSTRAINT "shopping_list_items_trip_id_fkey" FOREIGN KEY ("trip_id") REFERENCES "public"."trips"("id");
ALTER TABLE ONLY "public"."shopping_list_items" ADD CONSTRAINT "shopping_list_items_profile_id_fkey" FOREIGN KEY ("profile_id") REFERENCES "public"."profiles"("id");
ALTER TYPE "public"."resource_type" OWNER TO "postgres";

-- Define triggers
------------------------
CREATE OR REPLACE TRIGGER "handle_updated_at" BEFORE UPDATE ON "public"."shopping_list_items" FOR EACH ROW EXECUTE FUNCTION "extensions"."moddatetime"('updated_at');

-- Enable RLS
------------------------
ALTER TABLE "public"."shopping_list_items" ENABLE ROW LEVEL SECURITY;

-- Define policies
------------------------
-- Allow viewing shopping list items for trip members
CREATE POLICY "Trip members can view trip shopping list items" ON "public"."shopping_list_items"
FOR SELECT USING (
  EXISTS (
    SELECT 1 FROM trip_friends
    WHERE trip_friends.trip_id = shopping_list_items.trip_id
    AND trip_friends.profile_id = auth.uid()
    AND (
      trip_friends.role = 'OWNER' 
      OR (trip_friends.role = 'MEMBER' AND trip_friends.status = 'ACCEPTED')
    )
  )
);

-- Allow creating shopping list items (both USER and GROUP)
CREATE POLICY "Trip members can create shopping list items" ON "public"."shopping_list_items"
FOR INSERT WITH CHECK (
  CASE 
    WHEN resource_type = 'USER' THEN
      profile_id = auth.uid()
    WHEN resource_type = 'GROUP' THEN
      EXISTS (
        SELECT 1 FROM trip_friends
        WHERE trip_friends.trip_id = trip_id
        AND trip_friends.profile_id = auth.uid()
        AND (
          trip_friends.role = 'OWNER' 
          OR (trip_friends.role = 'MEMBER' AND trip_friends.status = 'ACCEPTED')
        )
      )
    ELSE
      false
  END
);

-- Allow updating your own USER shopping list items
CREATE POLICY "Users can manage their own shopping list items" ON "public"."shopping_list_items"
FOR UPDATE USING (
  resource_type = 'USER'
  AND profile_id = auth.uid()
);

-- Allow updating GROUP shopping list items for trip members
CREATE POLICY "Trip members can manage group shopping list items" ON "public"."shopping_list_items"
FOR UPDATE USING (
  resource_type = 'GROUP'
  AND EXISTS (
    SELECT 1 FROM trip_friends
    WHERE trip_friends.trip_id = shopping_list_items.trip_id
    AND trip_friends.profile_id = auth.uid()
    AND (
      trip_friends.role = 'OWNER' 
      OR (trip_friends.role = 'MEMBER' AND trip_friends.status = 'ACCEPTED')
    )
  )
);

-- Allow deleting your own USER shopping list items
CREATE POLICY "Users can delete their own shopping list items" ON "public"."shopping_list_items"
FOR DELETE USING (
  resource_type = 'USER'
  AND profile_id = auth.uid()
);

-- Allow deleting GROUP shopping list items for trip members
CREATE POLICY "Trip members can delete group shopping list items" ON "public"."shopping_list_items"
FOR DELETE USING (
  resource_type = 'GROUP'
  AND EXISTS (
    SELECT 1 FROM trip_friends
    WHERE trip_friends.trip_id = shopping_list_items.trip_id
    AND trip_friends.profile_id = auth.uid()
    AND (
      trip_friends.role = 'OWNER' 
      OR (trip_friends.role = 'MEMBER' AND trip_friends.status = 'ACCEPTED')
    )
  )
);

