-- Create categories table
------------------------
CREATE TABLE IF NOT EXISTS "public"."categories" (
    "id" bigint NOT NULL,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "name" character varying,
    "unit" character varying DEFAULT 'oz'::character varying,
    "slug" character varying,
    "pack_id" bigint,
    "position" integer NOT NULL DEFAULT 1,
    "updated_at" timestamp with time zone DEFAULT "now"() NOT NULL
);

-- Alter table statements
------------------------
ALTER TABLE "public"."categories" OWNER TO "postgres";
ALTER TABLE "public"."categories" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."categories_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY "public"."categories" ADD CONSTRAINT "categories_pkey" PRIMARY KEY ("id");
ALTER TABLE ONLY "public"."categories" ADD CONSTRAINT "categories_slug_key" UNIQUE ("slug");
ALTER TABLE ONLY "public"."categories" ADD CONSTRAINT "categories_pack_id_fkey" FOREIGN KEY ("pack_id") REFERENCES "public"."packs"("id") ON DELETE CASCADE;

-- Define indexes
CREATE INDEX idx_categories_pack_position ON "public"."categories"("pack_id", "position");

-- Define functions
CREATE OR REPLACE FUNCTION "public"."adjust_category_positions"()
RETURNS TRIGGER AS $$
BEGIN
    -- Increment positions of existing categories in the same pack
    UPDATE "public"."categories"
    SET position = position + 1
    WHERE pack_id = NEW.pack_id AND position >= NEW.position AND id != NEW.id;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

