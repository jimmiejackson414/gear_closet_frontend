-- Issue #42: existing-user email invites.
-- Unique (trip_id, profile_id) so duplicate pending rows cannot be inserted.
-- trip_invite_attempts is service-role only (rate-limit sends per user / trip).

-- ---------------------------------------------------------------------------
-- Deduplicate trip_friends before adding the unique constraint.
-- Keep ACCEPTED over PENDING over DECLINED, then the oldest row.
-- ---------------------------------------------------------------------------
WITH ranked AS (
  SELECT
    id,
    row_number() OVER (
      PARTITION BY trip_id, profile_id
      ORDER BY
        CASE status
          WHEN 'ACCEPTED'::public.trip_friend_status THEN 0
          WHEN 'PENDING'::public.trip_friend_status THEN 1
          ELSE 2
        END,
        id
    ) AS rn
  FROM public.trip_friends
  WHERE trip_id IS NOT NULL
)
DELETE FROM public.trip_friends
WHERE id IN (SELECT id FROM ranked WHERE rn > 1);

ALTER TABLE public.trip_friends
  ADD CONSTRAINT trip_friends_trip_id_profile_id_key UNIQUE (trip_id, profile_id);

CREATE INDEX IF NOT EXISTS profiles_lower_email_idx
  ON public.profiles (lower(email));

-- ---------------------------------------------------------------------------
-- Rate-limit log: no client policies; service_role bypasses RLS.
-- ---------------------------------------------------------------------------
CREATE TABLE public.trip_invite_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  trip_id bigint NOT NULL REFERENCES public.trips(id) ON DELETE CASCADE,
  email_count integer NOT NULL DEFAULT 1,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT trip_invite_attempts_email_count_positive CHECK (email_count > 0)
);

CREATE INDEX trip_invite_attempts_profile_created_idx
  ON public.trip_invite_attempts (profile_id, created_at DESC);

CREATE INDEX trip_invite_attempts_trip_created_idx
  ON public.trip_invite_attempts (trip_id, created_at DESC);

ALTER TABLE public.trip_invite_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trip_invite_attempts FORCE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.trip_invite_attempts FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.trip_invite_attempts_id_seq FROM PUBLIC, anon, authenticated;

GRANT ALL ON TABLE public.trip_invite_attempts TO service_role;
GRANT ALL ON SEQUENCE public.trip_invite_attempts_id_seq TO service_role;
