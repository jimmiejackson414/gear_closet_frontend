-- Define types and enums
------------------------
CREATE TYPE "public"."trip_friend_status" AS ENUM (
    'ACCEPTED',
    'DECLINED',
    'PENDING'
);
ALTER TYPE "public"."trip_friend_status" OWNER TO "postgres";

CREATE TYPE "public"."trip_friend_role" as ENUM (
  'OWNER',
  'MEMBER'
)
ALTER TYPE "public"."trip_friend_role" OWNER TO "postgres";

-- Create trip_friends table
------------------------
CREATE TABLE IF NOT EXISTS "public"."trip_friends" (
    "id" BIGINT NOT NULL,
    "trip_id" BIGINT,
    "accepted_invite_on" TIMESTAMP WITH TIME ZONE,
    "created_at" TIMESTAMP WITH TIME ZONE DEFAULT "now"(),
    "status" "public"."trip_friend_status" DEFAULT 'PENDING'::"public"."trip_friend_status",
    "profile_id" UUID NOT NULL, -- Represents the friend
    "invited_by_id" UUID, -- Represents the inviter
    "invite_token" CHARACTER VARYING,
    "role" "public"."trip_friend_role" DEFAULT 'MEMBER'::"public"."trip_friend_role" NOT NULL,
    "updated_at" TIMESTAMP WITH TIME ZONE DEFAULT "now"() NOT NULL
);

-- Alter trip_friends table
------------------------
ALTER TABLE "public"."trip_friends" OWNER TO "postgres";
ALTER TABLE "public"."trip_friends" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."trip_friends_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
ALTER TABLE ONLY "public"."trip_friends" ADD CONSTRAINT "trip_friends_pkey" PRIMARY KEY ("id");
ALTER TABLE ONLY "public"."trip_friends" ADD CONSTRAINT "trip_friends_trip_id_fkey" FOREIGN KEY ("trip_id") REFERENCES "public"."trips"("id") ON DELETE CASCADE;
ALTER TABLE ONLY "public"."trip_friends" ADD CONSTRAINT "trip_friends_profile_id_fkey" FOREIGN KEY ("profile_id") REFERENCES "public"."profiles"("id");
ALTER TABLE ONLY "public"."trip_friends" ADD CONSTRAINT "trip_friends_invited_by_id_fkey" FOREIGN KEY ("invited_by_id") REFERENCES "public"."profiles"("id");

-- Define triggers
------------------------
CREATE OR REPLACE TRIGGER "handle_updated_at" BEFORE UPDATE ON "public"."trip_friends" FOR EACH ROW EXECUTE FUNCTION "extensions"."moddatetime"('updated_at');

-- Enable RLS
------------------------
ALTER TABLE "public"."trip_friends" ENABLE ROW LEVEL SECURITY;

-- Define policies
------------------------
-- Allow viewing trip_friends records if you're a member of the trip
CREATE POLICY "Trip members can view trip_friends" ON "public"."trip_friends"
FOR SELECT USING (
  EXISTS (
    SELECT 1 FROM trip_friends tf
    WHERE tf.trip_id = trip_friends.trip_id
    AND tf.profile_id = auth.uid()
    AND (
      tf.role = 'OWNER'
      OR (tf.role = 'MEMBER' AND tf.status = 'ACCEPTED')
    )
  )
);

-- Allow creating trip_friends records if you're either:
-- 1. The trip owner inviting others
-- 2. A user joining with an invite token
CREATE POLICY "Allow invites and joins" ON "public"."trip_friends"
FOR INSERT WITH CHECK (
  (
    -- Trip owners can invite others
    EXISTS (
      SELECT 1 FROM trip_friends tf
      WHERE tf.trip_id = trip_id
      AND tf.profile_id = auth.uid()
      AND tf.role = 'OWNER'
    )
  ) OR (
    -- Users can join with an invite token
    profile_id = auth.uid()
    AND invite_token IS NOT NULL
  )
);

-- Allow updating your own trip_friend record (for accepting/declining invites)
CREATE POLICY "Users can update their own trip_friend status" ON "public"."trip_friends"
FOR UPDATE USING (
  profile_id = auth.uid()
) WITH CHECK (
  -- Only allow updating status and accepted_invite_on
  (
    CASE WHEN status IS DISTINCT FROM OLD.status 
      OR accepted_invite_on IS DISTINCT FROM OLD.accepted_invite_on
    THEN true
    ELSE false
    END
  )
);

-- Allow trip owners to update any trip_friend record in their trip
CREATE POLICY "Trip owners can update any trip_friend" ON "public"."trip_friends"
FOR UPDATE USING (
  EXISTS (
    SELECT 1 FROM trip_friends tf
    WHERE tf.trip_id = trip_friends.trip_id
    AND tf.profile_id = auth.uid()
    AND tf.role = 'OWNER'
  )
);

-- Allow users to delete their own trip_friend record (leaving a trip)
CREATE POLICY "Users can leave trips" ON "public"."trip_friends"
FOR DELETE USING (
  profile_id = auth.uid()
);

-- Allow trip owners to remove any member from their trip
CREATE POLICY "Trip owners can remove members" ON "public"."trip_friends"
FOR DELETE USING (
  EXISTS (
    SELECT 1 FROM trip_friends tf
    WHERE tf.trip_id = trip_friends.trip_id
    AND tf.profile_id = auth.uid()
    AND tf.role = 'OWNER'
  )
);

